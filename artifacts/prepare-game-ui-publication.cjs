const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),cp=require('node:child_process');
const root=process.cwd();
const git=(args,options={})=>cp.execFileSync('git',args,{cwd:root,...options});
const base=git(['rev-parse','origin/main']).toString().trim();
const patch=git(['diff','--binary','--','index.html','shared/toenow-i18n.js']);
if(!patch.length)throw Error('No UI changes found');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'toenow-game-ui-publish-'));
const env={...process.env,GIT_INDEX_FILE:path.join(temp,'publish.index')};
git(['read-tree',base],{env});
git(['apply','--cached','--check','-'],{env,input:patch});
git(['apply','--cached','-'],{env,input:patch});
const files=git(['diff','--cached','--name-only',base],{env}).toString().trim().split(/\r?\n/).sort();
if(JSON.stringify(files)!==JSON.stringify(['index.html','shared/toenow-i18n.js']))throw Error('Unexpected publication files: '+files);
const tree=git(['write-tree'],{env}).toString().trim();
const snapshot=path.join(temp,'snapshot');fs.mkdirSync(snapshot);
const archive=path.join(temp,'snapshot.tar');
git(['archive','--format=tar','--output='+archive,tree]);
cp.execFileSync('tar',['-xf',archive,'-C',snapshot]);
fs.writeFileSync(path.join(root,'artifacts/game-ui-publication-state.json'),JSON.stringify({base,tree,temp,snapshot,files},null,2));
console.log(JSON.stringify({base,tree,snapshot,files}));
const args=JSON.parse(fs.readFileSync(path.join(snapshot,'package.json'),'utf8')).scripts.test.split(/\s+/).slice(1);
const result=cp.spawnSync(process.execPath,args,{cwd:snapshot,encoding:'utf8',windowsHide:true,maxBuffer:12*1024*1024});
fs.writeFileSync(path.join(root,'artifacts/game-ui-publication-npm.log'),(result.stdout||'')+(result.stderr||''));
console.log((result.stdout||'').split(/\r?\n/).slice(-12).join('\n'));
if(result.error)throw result.error;
if(result.status!==0)throw Error('Snapshot tests failed: '+result.status);
